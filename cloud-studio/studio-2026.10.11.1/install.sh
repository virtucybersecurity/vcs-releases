#!/usr/bin/env bash
# Cloud Code Studio - Minimal Deploy
# Installs: gateway (:9000) + code-server (default tool) + cloudflared tunnel
# Everything else is installed on-demand via dashboard UI (gateway /api/install/:tool)
#
# Required env vars (passed from deploy route):
#   VCS_STUDIO_RPC_KEY    – credential scoped to this server only
#   VCS_API_URL           – VCS platform base URL
#   VCS_SERVER_ID         – server ID
#   VCS_SUBDOMAIN         – full subdomain (e.g. myserver.virtucomputing.com)
#   VCS_TUNNEL_TOKEN      – cloudflared tunnel token
# Optional:
#   VCS_CC_PORT           – code-server port (default: 9000)
#   VCS_CC_WORKSPACE      – workspace dir (default: /root)
#   VCS_CC_LOCAL_USERNAME – local fallback username (default: admin)
#   VCS_CC_LOCAL_PASSWORD – local fallback password generated by VCS App deploy
#   VCS_CC_CONFIGURE_LOCAL_AUTH – 1 only for first deploy; 0 preserves auth on update
#   VCS_CC_UI_VERSION / VCS_CC_UI_SHA256 – immutable distributed dashboard release

set -euo pipefail
umask 077

LOG="/var/log/vcs-cloud-code-install.log"
exec > >(tee -a "$LOG") 2>&1

log()  { echo "[$(date +%H:%M:%S)] $*"; }
warn() { echo "[$(date +%H:%M:%S)] WARNING: $*"; }
fail() { echo "[$(date +%H:%M:%S)] FATAL: $*"; exit 1; }



# ── Validate required env vars ───────────────────────────────────
VCS_API_URL="${VCS_API_URL:-}"
if [ -n "${VCS_SERVER_ID:-}" ]; then
  [ -n "${VCS_STUDIO_RPC_KEY:-}" ] || fail "Server-scoped Studio RPC key required"
  [ -n "${VCS_STUDIO_PUBLIC_KEY:-}" ] || fail "Studio public signing key required"
fi
[ -z "${VCS_SUBDOMAIN:-}" ]        && fail "VCS_SUBDOMAIN not set"

BIND_PORT="${VCS_CC_PORT:-8443}"
WORKSPACE="${VCS_CC_WORKSPACE:-/root}"
CODE_SERVER_CONFIG_DIR="/root/.config/code-server"
CODE_SERVER_CONFIG_FILE="${CODE_SERVER_CONFIG_DIR}/config.yaml"
GATEWAY_URL="${VCS_CC_GATEWAY_URL:-https://raw.githubusercontent.com/virtucybersecurity/vcs-releases/main/gateway/v1.1.42/gateway-go}"
AUTH_URL="https://raw.githubusercontent.com/virtucybersecurity/vcs-releases/main/vcs-cc-auth/v1.0.3/vcs-cc-auth"
GATEWAY_SHA256="${VCS_CC_GATEWAY_SHA256:-e8ba1ab89863659de37350240be2fc8e424fb9344963b148a28e9c7471532041}"
GATEWAY_VERSION="${VCS_CC_GATEWAY_VERSION:-v1.1.42}"
AUTH_SHA256="bc63be8331fb8a1bad58882ff273cbbd1555a0afe27711e97b2a961e20631fff"

log "=== Cloud Code Studio Minimal Deploy ==="
log "VCS_API_URL=$VCS_API_URL"
log "VCS_SUBDOMAIN=$VCS_SUBDOMAIN"
log "VCS_SERVER_ID=${VCS_SERVER_ID:-}"

# A legacy bridge is retired only when it has no child job/shell.
for svc in vcs-cc-terminal.service vcs-cc-agent.service; do
  PID=$(systemctl show "$svc" -p MainPID --value 2>/dev/null || true)
  if [[ "$PID" =~ ^[1-9][0-9]*$ ]] && pgrep -P "$PID" >/dev/null 2>&1; then
    fail "Active legacy Studio work in $svc. Explicitly finish or close it before upgrading."
  fi
done

# ── Directories ──────────────────────────────────────────────────
mkdir -p /opt/vcs-cloud-code 2>/dev/null || sudo mkdir -p /opt/vcs-cloud-code
chown -R "$(whoami):$(whoami)" /opt/vcs-cloud-code 2>/dev/null || sudo chown -R "$(whoami):$(whoami)" /opt/vcs-cloud-code
mkdir -p /opt/vcs-app/public/cloud-code 2>/dev/null || sudo mkdir -p /opt/vcs-app/public/cloud-code
mkdir -p /opt/vcs-app/logs 2>/dev/null || sudo mkdir -p /opt/vcs-app/logs

# Create Cloud Code Studio CLI tool directory
mkdir -p /opt/vcs-app/tools/cli-cloud-code/public

AUTH_PREEXISTING_USERS=0
if [ -f /opt/vcs-cc-auth/auth.db ]; then
  AUTH_PREEXISTING_USERS=$(python3 - <<'AUTHSTATE'
import sqlite3
c=sqlite3.connect('file:/opt/vcs-cc-auth/auth.db?mode=ro',uri=True)
print(c.execute('select count(*) from users').fetchone()[0])
AUTHSTATE
  )
fi

# Stage every executable before changing a service. Existing tools are retained.
exec 9>/opt/vcs-cloud-code/.install.lock
flock -n 9 || fail "Another Studio installer is running"
STAGE=$(mktemp -d /opt/vcs-cloud-code/.update-XXXXXXXX)
COMPLETED=0
snapshot() { python3 - "$STAGE" <<'SNAPSHOT'
from pathlib import Path
import json,shutil,sys
root=Path(sys.argv[1]); files=['/opt/vcs-cc-auth/vcs-cc-auth','/opt/vcs-cloud-code/gateway-go','/opt/vcs-cloud-code/gateway.conf','/opt/vcs-cloud-code/metadata.json','/opt/vcs-cloud-code/private/studio.env','/opt/vcs-cloud-code/tools.json','/etc/systemd/system/vcs-cc-auth.service','/etc/systemd/system/vcs-cc-gateway.service','/etc/systemd/system/vcs-cc-runtime.service']
state=[]
for i,n in enumerate(files):
 p=Path(n); present=p.is_file();state.append({'path':n,'present':present,'copy':str(i)})
 if present:shutil.copy2(p,root/str(i))
(root/'snapshot.json').write_text(json.dumps(state))
SNAPSHOT
}
rollback_update() {
 local result=$?
 if [ "$COMPLETED" != "1" ]; then
  python3 - "$STAGE" <<'RESTORE'
import json,shutil,sys
from pathlib import Path
root=Path(sys.argv[1]);manifest=root/'snapshot.json'
if manifest.exists():
 for item in json.loads(manifest.read_text()):
  p=Path(item['path'])
  if item['present']:p.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(root/item['copy'],p)
  elif p.is_file():p.unlink()
RESTORE
  systemctl daemon-reload
  for svc in vcs-cc-auth.service vcs-cc-gateway.service; do
   if [ -f "/etc/systemd/system/$svc" ]; then systemctl restart "$svc" || true; fi
  done
 fi
 python3 - "$STAGE" <<'CLEAN_STAGE'
from pathlib import Path
import sys,shutil
p=Path(sys.argv[1]);assert p.parent==Path('/opt/vcs-cloud-code') and p.name.startswith('.update-') and not p.is_symlink();shutil.rmtree(p)
CLEAN_STAGE
 return "$result"
}
snapshot
trap rollback_update EXIT
# Optional upstream prerequisites are pinned for first install only.
if ! command -v code-server >/dev/null; then
 [ "$(uname -m)" = "x86_64" ] || fail "This release supports x86_64"
 curl -fsSL https://github.com/coder/code-server/releases/download/v4.128.0/code-server_4.128.0_amd64.deb -o "$STAGE/code-server.deb"
 echo "c0f6e3706c4285f06bb2350274576f289262e6a9962a70e3c31c6d3ea17a29d2  $STAGE/code-server.deb" | sha256sum -c - >/dev/null
 dpkg -i "$STAGE/code-server.deb"
fi
if ! command -v cloudflared >/dev/null; then
 curl -fsSL https://github.com/cloudflare/cloudflared/releases/download/2026.9.1/cloudflared-linux-amd64 -o "$STAGE/cloudflared"
 echo "03f1f25d1cc93b9ad6c60569d44060bc4f17ed97075760ed8cfca4b12dcd68cc  $STAGE/cloudflared" | sha256sum -c - >/dev/null
 install -m 0755 "$STAGE/cloudflared" /usr/bin/cloudflared
fi
curl -fsSL "$AUTH_URL" -o "$STAGE/auth"
echo "$AUTH_SHA256  $STAGE/auth" | sha256sum -c - >/dev/null
curl -fsSL "$GATEWAY_URL" -o "$STAGE/gateway"
echo "$GATEWAY_SHA256  $STAGE/gateway" | sha256sum -c - >/dev/null
AUTH_URL="file://$STAGE/auth"
GATEWAY_URL="file://$STAGE/gateway"

# ── vcs-cc-auth ──────────────────────────────────────────────────
log "Installing vcs-cc-auth..."
mkdir -p /opt/vcs-cc-auth
AUTH_DOWNLOADED=false
AUTH_TMP="/opt/vcs-cc-auth/vcs-cc-auth.download"
if command -v curl >/dev/null; then
  if curl -fsSL "$AUTH_URL" -o "$AUTH_TMP"; then
    AUTH_DOWNLOADED=true
  else
    rm -f "$AUTH_TMP"
    warn "vcs-cc-auth download failed (curl)"
  fi
elif command -v wget >/dev/null; then
  if wget -q "$AUTH_URL" -O "$AUTH_TMP"; then
    AUTH_DOWNLOADED=true
  else
    rm -f "$AUTH_TMP"
    warn "vcs-cc-auth download failed (wget)"
  fi
else
  warn "curl/wget not available — cannot download vcs-cc-auth"
fi

if [ "$AUTH_DOWNLOADED" = true ]; then
  echo "$AUTH_SHA256  $AUTH_TMP" | sha256sum -c - >/dev/null || {
    rm -f "$AUTH_TMP"
    fail "vcs-cc-auth checksum verification failed"
  }
  mv "$AUTH_TMP" /opt/vcs-cc-auth/vcs-cc-auth
elif [ -x /opt/vcs-cc-auth/vcs-cc-auth ]; then
  [ "$(sha256sum /opt/vcs-cc-auth/vcs-cc-auth | cut -d' ' -f1)" = "$AUTH_SHA256" ] || fail "Pinned Auth release unavailable"
else
  warn "Skipping vcs-cc-auth setup — binary not available"
fi

if [ -f /opt/vcs-cc-auth/vcs-cc-auth ]; then
  chmod +x /opt/vcs-cc-auth/vcs-cc-auth
else
  warn "vcs-cc-auth service not configured — binary not available"
fi

if [ -x /opt/vcs-cc-auth/vcs-cc-auth ]; then

  cat > /etc/systemd/system/vcs-cc-auth.service << AUTHEOF
[Unit]
Description=VCS Cloud Code Studio Auth Service
After=network.target
Before=vcs-cc-gateway.service

[Service]
Type=simple
User=root
WorkingDirectory=/opt/vcs-cc-auth
ExecStart=/opt/vcs-cc-auth/vcs-cc-auth
Restart=always
RestartSec=3
RuntimeDirectory=vcs-cc-auth
RuntimeDirectoryMode=0750

[Install]
WantedBy=multi-user.target
AUTHEOF

  systemctl daemon-reload 2>/dev/null || sudo systemctl daemon-reload
  systemctl enable vcs-cc-auth.service 2>/dev/null || sudo systemctl enable vcs-cc-auth.service
  AUTH_PID=$(systemctl show vcs-cc-auth.service -p MainPID --value 2>/dev/null || true)
  if [[ "$AUTH_PID" =~ ^[1-9][0-9]*$ ]] && [ "$(sha256sum /proc/$AUTH_PID/exe | cut -d' ' -f1)" = "$AUTH_SHA256" ]; then
    log "Auth executable already current"
  else
    systemctl restart vcs-cc-auth.service
  fi
  sleep 2
  if curl -sf --unix-socket /run/vcs-cc-auth/auth.sock http://local/health >/dev/null 2>&1; then
    log "vcs-cc-auth: healthy"
  else
    warn "vcs-cc-auth health check failed — check: journalctl -u vcs-cc-auth"
  fi

  if [ "$AUTH_PREEXISTING_USERS" != "0" ]; then VCS_CC_CONFIGURE_LOCAL_AUTH=0; fi
  if [ "${VCS_CC_CONFIGURE_LOCAL_AUTH:-1}" = "1" ] && [ -n "${VCS_CC_LOCAL_PASSWORD:-}" ]; then
    LOCAL_USER="${VCS_CC_LOCAL_USERNAME:-admin}"
    log "Configuring local fallback auth user: ${LOCAL_USER}"

    for _ in $(seq 1 20); do
      [ -S /run/vcs-cc-auth/auth.sock ] && break
      sleep 1
    done
    [ -S /run/vcs-cc-auth/auth.sock ] || fail "vcs-cc-auth socket not found"

    REG_PAYLOAD="$(
      VCS_LOCAL_USER="$LOCAL_USER" VCS_LOCAL_PASSWORD="$VCS_CC_LOCAL_PASSWORD" python3 - <<'PYEOF'
import json, os
print(json.dumps({
    "username": os.environ["VCS_LOCAL_USER"],
    "password": os.environ["VCS_LOCAL_PASSWORD"],
    "reset_totp": True,
}))
PYEOF
    )"
    curl -sf --unix-socket /run/vcs-cc-auth/auth.sock \
      -H 'Content-Type: application/json' \
      -d "$REG_PAYLOAD" \
      http://local/api/v1/auth/register >/dev/null
    rm -f /opt/vcs-cc-auth/initial-credentials
    unset REG_PAYLOAD VCS_CC_LOCAL_PASSWORD
    echo "VCS_CLOUD_STUDIO_LOCAL_AUTH provisioned"
    log "Local fallback auth user ready: ${LOCAL_USER}"
  elif [ "${VCS_CC_CONFIGURE_LOCAL_AUTH:-1}" = "0" ]; then
    echo "VCS_CLOUD_STUDIO_LOCAL_AUTH preserved"
    log "Preserving existing local auth account, password, TOTP, and recovery codes"
  else
    warn "VCS_CC_LOCAL_PASSWORD not set — local fallback auth user not configured"
  fi
fi

# ── Go gateway binary ────────────────────────────────────────────
log "Downloading Go gateway binary..."
GW_DOWNLOADED=false
GW_TMP="/opt/vcs-cloud-code/gateway-go.download"
if command -v curl >/dev/null; then
  if curl -fsSL "$GATEWAY_URL" -o "$GW_TMP"; then
    GW_DOWNLOADED=true
  else
    rm -f "$GW_TMP"
    warn "Gateway download failed (curl)"
  fi
elif command -v wget >/dev/null; then
  if wget -q "$GATEWAY_URL" -O "$GW_TMP"; then
    GW_DOWNLOADED=true
  else
    rm -f "$GW_TMP"
    warn "Gateway download failed (wget)"
  fi
else
  warn "curl/wget not available — cannot download gateway"
fi

if [ "$GW_DOWNLOADED" = true ]; then
  echo "$GATEWAY_SHA256  $GW_TMP" | sha256sum -c - >/dev/null || {
    rm -f "$GW_TMP"
    fail "gateway checksum verification failed"
  }
  mv "$GW_TMP" /opt/vcs-cloud-code/gateway-go
elif [ -x /opt/vcs-cloud-code/gateway-go ]; then
  [ "$(sha256sum /opt/vcs-cloud-code/gateway-go | cut -d' ' -f1)" = "$GATEWAY_SHA256" ] || fail "Pinned gateway release unavailable"
else
  warn "Skipping gateway setup — binary not available"
fi

if [ -f /opt/vcs-cloud-code/gateway-go ]; then
  chmod +x /opt/vcs-cloud-code/gateway-go
  GATEWAY_RUNTIME_SHA256="$(sha256sum /opt/vcs-cloud-code/gateway-go | awk '{print $1}')"
  UI_RUNTIME_SHA256="$(sha256sum /opt/vcs-app/public/cloud-code/index.html | awk '{print $1}')"
  [ -n "${VCS_CC_UI_SHA256:-}" ] && [ "$UI_RUNTIME_SHA256" != "$VCS_CC_UI_SHA256" ] && fail "Studio UI checksum verification failed"
  cat > /opt/vcs-cloud-code/metadata.json << METAEOF
{"gatewayVersion":"${GATEWAY_VERSION}","gatewaySha256":"${GATEWAY_RUNTIME_SHA256}","uiVersion":"${VCS_CC_UI_VERSION:-unknown}","uiSha256":"${UI_RUNTIME_SHA256}"}
METAEOF
else
  warn "Gateway service not configured — binary not available"
fi


if [ -x /opt/vcs-cloud-code/gateway-go ]; then
  log "Gateway binary ready: /opt/vcs-cloud-code/gateway-go"

  cat > /opt/vcs-cloud-code/gateway.conf << GWCONF
INSTALL_PATH=/opt/vcs-cloud-code
PORT=9000
BIND_HOST=127.0.0.1
DOMAIN=${VCS_SUBDOMAIN}
LOG_DIR=/var/log/vcs
AUTH_SOCKET=/run/vcs-cc-auth/auth.sock
TOOLS_FILE=/opt/vcs-cloud-code/tools.json
SERVER_INFO_PATH=/opt/vcs-cloud-code/server.json
DB_PATH=/opt/vcs-cloud-code/vcs.db
DASHBOARD_DIR=/opt/vcs-app/public/cloud-code
GWCONF
  chmod 0644 /opt/vcs-cloud-code/gateway.conf

  install -d -m 0700 /opt/vcs-cloud-code/private
  python3 - <<'PRIVATEENV'
import json,os
keys=["VCS_API_URL","VCS_SERVER_ID","VCS_STUDIO_RPC_KEY","VCS_STUDIO_PUBLIC_KEY","VCS_STUDIO_CREDENTIAL_VERSION","VCS_CC_WORKSPACE"]
values={key:os.environ.get(key,"") for key in keys}
values["VCS_STUDIO_RUNTIME_SOCKET"]="/run/vcs-cc-runtime/runtime.sock"
path="/opt/vcs-cloud-code/private/studio.env"
with open(path+".new","w") as stream:
 for key,value in values.items(): stream.write(key+"="+json.dumps(value)+"\n")
os.chmod(path+".new",0o600);os.replace(path+".new",path)
PRIVATEENV
  # ── Gateway systemd service ──────────────────────────────────────
  cat > /etc/systemd/system/vcs-cc-gateway.service << GWEOF
[Unit]
Description=VCS Cloud Code Studio Auth Gateway
After=network.target vcs-cc-auth.service
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
ExecStart=/opt/vcs-cloud-code/gateway-go --config /opt/vcs-cloud-code/gateway.conf
WorkingDirectory=/opt/vcs-cloud-code
EnvironmentFile=/opt/vcs-cloud-code/private/studio.env
UMask=0077
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal
SyslogIdentifier=vcs-cc-gateway

[Install]
WantedBy=multi-user.target
GWEOF

  systemctl daemon-reload 2>/dev/null || sudo systemctl daemon-reload
  systemctl enable vcs-cc-gateway.service 2>/dev/null || sudo systemctl enable vcs-cc-gateway.service
  systemctl restart vcs-cc-gateway.service 2>/dev/null || sudo systemctl restart vcs-cc-gateway.service
  sleep 2
  if systemctl is-active --quiet vcs-cc-gateway.service; then
    log "Gateway: running on 127.0.0.1:9000"
  else
    warn "Gateway may still be starting"
    journalctl -u vcs-cc-gateway.service --no-pager -n 20
  fi
fi

# ── code-server (default tool) ──────────────────────────────────
if ! command -v code-server &>/dev/null; then
  fail "code-server is required; install the approved pinned package before Cloud Code Studio"
fi

if command -v code-server &>/dev/null; then
  CS_BIN=$(command -v code-server)
  log "code-server: $($CS_BIN --version 2>/dev/null | head -1)"

  mkdir -p "$CODE_SERVER_CONFIG_DIR"
  cat > "$CODE_SERVER_CONFIG_FILE" << CFGEOF
bind-addr: 127.0.0.1:${BIND_PORT}
auth: none
cert: false
disable-telemetry: true
disable-update-check: false
CFGEOF

  cat > /etc/systemd/system/vcs-cloud-code.service << CSEOF
[Unit]
Description=code-server VS Code IDE
After=network.target

[Service]
Type=simple
ExecStart=${CS_BIN} --config ${CODE_SERVER_CONFIG_FILE} ${WORKSPACE}
WorkingDirectory=${WORKSPACE}
Restart=always
RestartSec=5
Environment=HOME=/root

[Install]
WantedBy=multi-user.target
CSEOF
  systemctl daemon-reload 2>/dev/null || sudo systemctl daemon-reload

  systemctl enable vcs-cloud-code.service 2>/dev/null || sudo systemctl enable vcs-cloud-code.service
  if ! systemctl is-active --quiet vcs-cloud-code.service; then systemctl start vcs-cloud-code.service; else log "Existing IDE kept running"; fi
  log "code-server: running on :${BIND_PORT}"
fi

# One canonical Go runtime serves terminal/CLI and owns detached tool jobs.
# Upgrades must leave an active runtime process in place; no forced worker restart.
cat > /etc/systemd/system/vcs-cc-runtime.service <<'RUNTIMEUNIT'
[Unit]
Description=VCS Cloud Code Studio private work runtime
After=network.target
[Service]
Type=simple
WorkingDirectory=/opt/vcs-cloud-code
ExecStart=/opt/vcs-cloud-code/gateway-go --runtime
EnvironmentFile=/opt/vcs-cloud-code/private/studio.env
Environment=HOME=/root
Environment=PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/root/.local/bin
RuntimeDirectory=vcs-cc-runtime
RuntimeDirectoryMode=0700
UMask=0077
Restart=on-failure
RestartSec=3
[Install]
WantedBy=multi-user.target
RUNTIMEUNIT
systemctl daemon-reload
systemctl enable vcs-cc-runtime.service
if ! systemctl is-active --quiet vcs-cc-runtime.service; then
  systemctl start vcs-cc-runtime.service
else
  # Never let a gateway/UI update terminate detached shells or commands.
  ACTIVE=$(curl -fsS --unix-socket /run/vcs-cc-runtime/runtime.sock http://runtime/health | python3 -c 'import json,sys;print(json.load(sys.stdin)["active"])')
  if [ "$ACTIVE" = "0" ]; then systemctl restart vcs-cc-runtime.service; else log "Private work runtime retained: $ACTIVE active sessions/jobs"; fi
fi
for svc in vcs-cc-terminal.service vcs-cc-agent.service vcs-cc-claude.service; do
  systemctl disable --now "$svc" 2>/dev/null || true
  rm -f "/etc/systemd/system/$svc"
done
rm -f /opt/vcs-cloud-code/vcs-terminal-server.py /opt/vcs-cloud-code/vcs-cli-agent-server.py
log "Terminal and CLI: private runtime ready"

CODE_SERVER_AVAILABLE=0
if command -v code-server &>/dev/null; then
  CODE_SERVER_AVAILABLE=1
fi

VCS_CODE_SERVER_AVAILABLE="$CODE_SERVER_AVAILABLE" VCS_BIND_PORT="$BIND_PORT" python3 <<'PYEOF'
import json
import os

path = "/opt/vcs-cloud-code/tools.json"
bind_port = int(os.environ.get("VCS_BIND_PORT") or "8443")
code_available = os.environ.get("VCS_CODE_SERVER_AVAILABLE") == "1"

defaults = {
    "code-server": {
        "key": "code-server",
        "name": "VS Code",
        "description": "Browser-based VS Code workspace",
        "pathPrefix": "code",
        "port": bind_port,
        "stripPrefix": True,
        "systemd": "vcs-cloud-code",
        "label": "VS Code IDE",
    },
    "terminal": {
        "key": "terminal",
        "name": "Terminal",
        "description": "Standalone VCS-style shell for Cloud Code Studio fallback access",
        "pathPrefix": "terminal",
        "port": 7684,
        "stripPrefix": True,
        "systemd": "",
        "label": "Terminal",
    },
    "cli-chat": {
        "key": "cli-chat",
        "name": "CLI Chat",
        "description": "Embedded CLI chat stream",
        "pathPrefix": "cli",
        "port": 7683,
        "stripPrefix": True,
        "systemd": "",
        "label": "CLI Chat",
    },
}

existing = []
try:
    with open(path, "r", encoding="utf-8") as handle:
        parsed = json.load(handle)
        if isinstance(parsed, list):
            existing = [item for item in parsed if isinstance(item, dict) and item.get("key")]
except Exception:
    existing = []

by_key = {item["key"]: item for item in existing}
ordered = []

if code_available:
    ordered.append(defaults["code-server"])
elif "code-server" in by_key:
    ordered.append(by_key["code-server"])

for key in ("terminal", "cli-chat"):
    ordered.append(defaults[key])

for item in existing:
    key = item.get("key")
    if key not in {"code-server", "terminal", "signup", "ttyd", "glances", "claude-cli", "cli-chat"}:
        ordered.append(item)

tmp = path + ".tmp"
with open(tmp, "w", encoding="utf-8") as handle:
    json.dump(ordered, handle, separators=(",", ":"))
    handle.write("\n")
os.replace(tmp, path)
PYEOF

if [ "$CODE_SERVER_AVAILABLE" = "1" ]; then
  log "tools.json merged with code-server, terminal and chat stream entries"
else
  warn "code-server not currently available — preserved existing tools.json code-server entry if present"
fi

# ── cloudflared ──────────────────────────────────────────────────
if ! command -v cloudflared &>/dev/null; then
  fail "cloudflared is required; install the approved pinned package before Cloud Code Studio"
fi
command -v cloudflared &>/dev/null && log "cloudflared: $(cloudflared --version 2>/dev/null | head -1)" || warn "cloudflared not found"

# Migrate an existing Studio token privately; never write it to the journal.
if [ -z "${VCS_TUNNEL_TOKEN:-}" ] && [ -f /etc/systemd/system/vcs-cloud-code-tunnel.service ]; then
 VCS_TUNNEL_TOKEN=$(python3 - <<'MIGRATE_TOKEN'
from pathlib import Path
import shlex
private=Path('/opt/vcs-cloud-code/private/tunnel.token')
if private.is_file():print(private.read_text(),end='')
else:
 for line in Path('/etc/systemd/system/vcs-cloud-code-tunnel.service').read_text().splitlines():
  if line.startswith('ExecStart='):
   args=shlex.split(line.split('=',1)[1])
   if '--token' in args:print(args[args.index('--token')+1],end='')
MIGRATE_TOKEN
 )
fi
# ── Cloudflare tunnel ────────────────────────────────────────────
if [ -n "${VCS_TUNNEL_TOKEN:-}" ]; then
  log "Setting up cloudflared tunnel service..."

  # Remove stale Caddy config if present
  if [ -f /etc/caddy/conf.d/cloud-code.caddy ]; then
    rm -f /etc/caddy/conf.d/cloud-code.caddy
    systemctl reload caddy 2>/dev/null || true
    log "Removed stale Caddy config"
  fi

  install -d -m 0700 /opt/vcs-cloud-code/private
  printf %s "$VCS_TUNNEL_TOKEN" > /opt/vcs-cloud-code/private/tunnel.token
  chmod 0600 /opt/vcs-cloud-code/private/tunnel.token
  cat > /etc/systemd/system/vcs-cloud-code-tunnel.service << TUNEOF
[Unit]
Description=VCS Cloud Code Studio Cloudflare Tunnel
After=network-online.target vcs-cc-gateway.service
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/bin/cloudflared tunnel --no-autoupdate run --token-file /opt/vcs-cloud-code/private/tunnel.token
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal
SyslogIdentifier=vcs-cc-tunnel

[Install]
WantedBy=multi-user.target
TUNEOF

  systemctl daemon-reload 2>/dev/null || sudo systemctl daemon-reload
  systemctl enable vcs-cloud-code-tunnel.service 2>/dev/null || sudo systemctl enable vcs-cloud-code-tunnel.service
  if ! systemctl is-active --quiet vcs-cloud-code-tunnel.service; then
    systemctl start vcs-cloud-code-tunnel.service 2>/dev/null || sudo systemctl start vcs-cloud-code-tunnel.service
    sleep 3
  else
    log "Cloudflare tunnel already running — skipping restart"
  fi

  if systemctl is-active --quiet vcs-cloud-code-tunnel.service; then
    log "Cloudflare tunnel: active"
  else
    warn "Tunnel may still be connecting..."
    journalctl -u vcs-cloud-code-tunnel.service --no-pager -n 5
  fi
else
  warn "VCS_TUNNEL_TOKEN not set — skipping tunnel setup"
fi

